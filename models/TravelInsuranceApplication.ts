import mongoose from 'mongoose';

const travelInsuranceApplicationSchema = new mongoose.Schema({
  userId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true
  },
  insuranceId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'TravelInsurance',
    required: true
  },
  trackingId: {
    type: String,
    required: false, // Will be auto-generated by pre-save hook
    unique: true,
    index: true
  },
  personalInfo: {
    firstName: {
      type: String,
      required: true
    },
    lastName: {
      type: String,
      required: true
    },
    email: {
      type: String,
      required: true
    },
    phone: {
      type: String,
      required: true
    },
    dateOfBirth: {
      type: Date,
      required: true
    },
    nationality: {
      type: String,
      required: true
    },
    passportNumber: {
      type: String,
      required: true
    },
    passportExpiry: {
      type: Date,
      required: true
    }
  },
  tripDetails: {
    destination: {
      type: String,
      required: true
    },
    purpose: {
      type: String,
      enum: ['leisure', 'business', 'education', 'medical', 'other'],
      required: true
    },
    startDate: {
      type: Date,
      required: true
    },
    endDate: {
      type: Date,
      required: true
    },
    numberOfTravelers: {
      type: Number,
      required: true,
      min: 1
    }
  },
  documents: {
    passport: {
      type: String, // Cloudinary URL
      required: true
    },
    photo: {
      type: String, // Cloudinary URL
      required: true
    },
    visa: {
      type: String, // Cloudinary URL (optional)
      required: false
    }
  },
  selectedPlan: {
    planType: {
      type: String,
      enum: ['basic', 'standard', 'premium', 'family'],
      required: true
    },
    coverage: {
      medicalExpenses: Number,
      tripCancellation: Number,
      baggageLoss: Number,
      flightDelay: Number,
      personalAccident: Number
    },
    duration: Number, // in days
    totalPremium: Number
  },
  status: {
    type: String,
    enum: ['pending', 'approved', 'active', 'expired', 'cancelled'],
    default: 'pending'
  },
  paymentStatus: {
    type: String,
    enum: ['pending', 'completed', 'failed'],
    default: 'pending'
  },
  paymentMethod: {
    type: String,
    enum: ['upi', 'card', 'razorpay'],
    required: false
  },
  totalAmount: {
    type: Number,
    required: true
  },
  policyNumber: String,
  policyStartDate: Date,
  policyEndDate: Date,
  notes: String,
  agentId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User'
  }
}, {
  timestamps: true
});

// Pre-save hook to generate tracking ID
travelInsuranceApplicationSchema.pre('save', async function(next) {
  if (!this.trackingId) {
    const date = new Date();
    const dateStr = date.getFullYear().toString() + 
                   (date.getMonth() + 1).toString().padStart(2, '0') + 
                   date.getDate().toString().padStart(2, '0');
    
    // Generate random 5-character string
    const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
    let randomStr = '';
    for (let i = 0; i < 5; i++) {
      randomStr += chars.charAt(Math.floor(Math.random() * chars.length));
    }
    
    this.trackingId = `TI-${dateStr}-${randomStr}`;
  }
  next();
});

export default mongoose.models.TravelInsuranceApplication || mongoose.model('TravelInsuranceApplication', travelInsuranceApplicationSchema);
